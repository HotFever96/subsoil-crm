import { NextRequest, NextResponse } from "next/server";
import { callOpenRouter } from "@/lib/openrouter";
import { AGENT_PROFILES } from "@/lib/agent-profiles";
import { SubAgentRole } from "@/lib/project-types";

export async function POST(req: NextRequest) {
  try {
    const {
      role,
      subSectionCode,
      subSectionTitle,
      currentContent,
      instruction,
      parameters,
      projectMetadata,
    } = await req.json();

    const selectedRole: SubAgentRole = (role as SubAgentRole) || "ENGINEER";
    const agentProfile = AGENT_PROFILES[selectedRole] || AGENT_PROFILES.ENGINEER;

    const systemPrompt = `${agentProfile.systemPrompt}

ДОПОЛНИТЕЛЬНЫЕ ИНСТРУКЦИИ ДЛЯ СУБАГЕНТА (РЕЖИМ ИНЖЕНЕРНОГО РАСЧЕТА И ОПРОСНИКА):
- Ты работаешь в мультиагентной среде проектирования открытых горных работ (ТПР ОПИ: песок, ПГС, щебень) Geo AI.
- Категорически ЗАПРЕЩЕНО писать выдуманные абстрактные данные («с потолка»).
- Строго используй фактические значения из опросника инженера (параметры, предоставленные пользователем).
- Производи расчеты по утвержденным формулам:
  * Ширина бермы безопасности по ФНиП Ростехнадзора № 505: Бб = 0.2 * hу + 2.5 м;
  * Срок службы карьера: Т = Zпром / Агод;
  * Объем нанесения почвенно-растительного слоя: Vпрс = Sрек * hпрс * 10 000;
  * Время цикла автосамосвала и потребный парк техники.
- Твой ответ ДОЛЖЕН быть строго в формате JSON:
{
  "content": "Полный, глубоко проработанный инженерный текст подраздела в Markdown с формулами, таблицами, технологическими регламентами",
  "explanation": "Твой экспертный комментарий с обоснованием принятых формул, нормативов безопасности и расчетов",
  "normativeBase": ["Массив из 2-4 конкретных НПА, ГОСТов или ФНиП Ростехнадзора"]
}
Не добавляй никакого текста вне JSON-блока.`;

    let userPrompt = `Объект проектирования:
- Проект: "${projectMetadata?.title || "Технический проект разработки месторождения ОПИ"}"
- Лицензия: ${projectMetadata?.licenseCode && projectMetadata.licenseCode !== "—" ? projectMetadata.licenseCode : "Уточняется"}
- Месторождение: ${projectMetadata?.depositName && projectMetadata.depositName !== "—" ? projectMetadata.depositName : "Уточняется"}
- Вид ископаемого: ${projectMetadata?.mineralType && projectMetadata.mineralType !== "—" ? projectMetadata.mineralType : "Песок строительный"}

Текущий подраздел проекта:
Код: ${subSectionCode}
Название: "${subSectionTitle}"
`;

    if (parameters && typeof parameters === "object" && Object.keys(parameters).length > 0) {
      userPrompt += `\nФАКТИЧЕСКИЕ ИСХОДНЫЕ ДАННЫЕ (ответы горного инженера на вопросы опросника):\n`;
      for (const [key, val] of Object.entries(parameters)) {
        if (val !== undefined && val !== null && String(val).trim().length > 0) {
          userPrompt += `- ${key}: ${val}\n`;
        }
      }
    }

    if (currentContent) {
      userPrompt += `\nТекущий текст раздела:\n${currentContent}\n`;
    }

    userPrompt += `\nЗадание инженеру:\n${instruction || "На основе предоставленных выше исходных данных произведи строгие расчеты по формулам правил безопасности (ФНиП Ростехнадзора № 505 / Постановление № 800 / ГОСТ 8736-2014), сформируй инженерно-технический текст подраздела с расчетными таблицами и ссылками на нормативные правовые акты РФ."}`;

    const openRouterResponse = await callOpenRouter({
      model: "anthropic/claude-3.5-sonnet",
      messages: [
        { role: "system", content: systemPrompt },
        { role: "user", content: userPrompt },
      ],
      temperature: 0.15,
      max_tokens: 3500,
    });

    if (openRouterResponse?.choices?.[0]?.message?.content) {
      const rawText = openRouterResponse.choices[0].message.content.trim();
      try {
        let jsonStr = rawText;
        if (rawText.includes("```json")) {
          jsonStr = rawText.split("```json")[1].split("```")[0].trim();
        } else if (rawText.includes("```")) {
          jsonStr = rawText.split("```")[1].split("```")[0].trim();
        }
        const parsed = JSON.parse(jsonStr);
        return NextResponse.json({
          content: parsed.content,
          explanation: parsed.explanation,
          normativeBase: parsed.normativeBase || agentProfile.normativeCompetencies.slice(0, 3),
          source: "openrouter-claude-3.5",
        });
      } catch {
        return NextResponse.json({
          content: rawText,
          explanation: `Специалист (${agentProfile.title}) произвел расчет и сформировал подраздел на основании ваших исходных данных.`,
          normativeBase: agentProfile.normativeCompetencies.slice(0, 3),
          source: "openrouter-claude-3.5",
        });
      }
    }

    // High quality offline domain intelligence fallback
    const offlineResult = generateOfflineSubagentResponse(
      selectedRole,
      subSectionCode,
      subSectionTitle,
      instruction,
      parameters,
      projectMetadata
    );

    return NextResponse.json({
      ...offlineResult,
      source: "local-domain-intelligence",
    });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : "Error";
    return NextResponse.json({ error: message }, { status: 500 });
  }
}

